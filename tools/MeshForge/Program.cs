// MeshForge entry point: builds every part's meshes, writes the OBJ files (one per part, and
// AllParts.obj for a single import), the Luau placement table and a preview sheet per part.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

public class MeshSpec
{
	public string Name, Material;
	public List<string> Groups = new List<string>(); // joint groups it rides on (one entry each)
	public bool Local;          // authored relative to its group's pivot frame (else the part frame)
	public double Transparency;
	public Sdf Shape;
	public int[] Color;
	public double Voxel = 0.05;
	public int Budget = 2500; // triangles after simplification
	public MeshSpec(string name, Sdf shape, int[] color, string material) { Name = name; Shape = shape; Color = color; Material = material; }
}

// X mirror of a shape (left limbs, left wings).
public class Flip : Sdf
{
	Sdf s;
	public Flip(Sdf s) { this.s = s; }
	public override double D(V3 p) { return s.D(new V3(-p.X, p.Y, p.Z)); }
	public override void Bounds(ref V3 lo, ref V3 hi)
	{
		V3 l = new V3(1e9, 1e9, 1e9), h = new V3(-1e9, -1e9, -1e9);
		s.Bounds(ref l, ref h);
		lo = new V3(Math.Min(lo.X, -h.X), Math.Min(lo.Y, l.Y), Math.Min(lo.Z, l.Z));
		hi = new V3(Math.Max(hi.X, -l.X), Math.Max(hi.Y, h.Y), Math.Max(hi.Z, h.Z));
	}
}

public class PartSpec
{
	public string Id;
	public bool ArmMirror; // an arm: the assembler mirrors the whole part on the left side
	public Dictionary<string, V3> GroupPivots = new Dictionary<string, V3>();
	public Dictionary<string, V3> GroupRots = new Dictionary<string, V3>();
	public List<MeshSpec> Meshes = new List<MeshSpec>();
	public PartSpec(string id) { Id = id; }
	public void Group(string name, V3 pivot, V3 rot) { GroupPivots[name] = pivot; GroupRots[name] = rot; }
	public void Group(string name, V3 pivot) { Group(name, pivot, new V3(0, 0, 0)); }
	// authored in the PART frame
	public MeshSpec Add(string name, Sdf shape, int[] color, string material, string group = null, double voxel = 0.05, int budget = 2500)
	{
		var m = new MeshSpec(Id + "_" + name, shape, color, material) { Voxel = voxel, Budget = budget };
		if (group != null) m.Groups.Add(group);
		Meshes.Add(m);
		return m;
	}
	// authored in a GROUP's own frame; used on every group listed
	public MeshSpec AddLocal(string name, Sdf shape, int[] color, string material, string[] groups, double voxel = 0.05, int budget = 2500)
	{
		var m = new MeshSpec(Id + "_" + name, shape, color, material) { Voxel = voxel, Budget = budget, Local = true };
		m.Groups.AddRange(groups);
		Meshes.Add(m);
		return m;
	}
	// a right-side mesh (on the right groups) and its mirror image (on the left groups)
	public void AddPair(string name, Sdf right, int[] color, string material, string[] rightGroups, string[] leftGroups, bool local, double voxel = 0.05, int budget = 2500, double transparency = 0)
	{
		var r = new MeshSpec(Id + "_" + name, right, color, material) { Voxel = voxel, Budget = budget, Local = local, Transparency = transparency };
		r.Groups.AddRange(rightGroups);
		var l = new MeshSpec(Id + "_" + name + "_L", new Flip(right), color, material) { Voxel = voxel, Budget = budget, Local = local, Transparency = transparency };
		l.Groups.AddRange(leftGroups);
		Meshes.Add(r);
		Meshes.Add(l);
	}
}

public static class Program
{
	static string F(double d) { return d.ToString("0.#####", CultureInfo.InvariantCulture); }

	static MeshData Place(MeshData m, Rot r, V3 t)
	{
		var o = new MeshData();
		foreach (var v in m.V) o.V.Add(r.Apply(v) + t);
		foreach (var n in m.N) o.N.Add(r.Apply(n));
		o.T.AddRange(m.T);
		return o;
	}

	static void WriteObject(StringBuilder obj, string name, MeshData mesh, V3 center, ref int vBase)
	{
		// (Studio's importer splits an OBJ into MeshParts by group, so name both)
		obj.AppendLine("o " + name);
		obj.AppendLine("g " + name);
		foreach (var v in mesh.V) obj.AppendLine("v " + F(v.X - center.X) + " " + F(v.Y - center.Y) + " " + F(v.Z - center.Z));
		foreach (var n in mesh.N) obj.AppendLine("vn " + F(n.X) + " " + F(n.Y) + " " + F(n.Z));
		for (int t = 0; t < mesh.T.Count; t += 3)
		{
			int a = mesh.T[t] + vBase, b = mesh.T[t + 1] + vBase, c = mesh.T[t + 2] + vBase;
			obj.AppendLine("f " + a + "//" + a + " " + b + "//" + b + " " + c + "//" + c);
		}
		vBase += mesh.V.Count;
	}

	public static int Main(string[] args)
	{
		string outDir = args.Length > 0 ? args[0] : "out";
		Directory.CreateDirectory(outDir);
		var only = new HashSet<string>();
		for (int i = 1; i < args.Length; i++) only.Add(args[i]);
		var lua = new StringBuilder();
		lua.AppendLine("--[[");
		lua.AppendLine("\tPartMeshes  (ModuleScript, GENERATED by tools/MeshForge: do not edit by hand)");
		lua.AppendLine("\tLocation: ReplicatedStorage/Shared/PartMeshes");
		lua.AppendLine("");
		lua.AppendLine("\tThe sculpted look of every Nightmare part: for each part, its meshes (templates in");
		lua.AppendLine("\tShared/Meshes), each with its centre and size in the part's frame - or in its joint");
		lua.AppendLine("\tGroup's frame - and its colour and material. NightmareAssembler builds a part from");
		lua.AppendLine("\tthese when its templates exist, else from PartDefinitions' block pieces. An arm's");
		lua.AppendLine("\tmeshes also exist as <Mesh>_L, the mirror image for a left arm.");
		lua.AppendLine("]]");
		lua.AppendLine("return {");
		var all = new StringBuilder();
		int allBase = 1;
		int totalTris = 0;
		foreach (var part in Parts.All())
		{
			if (only.Count > 0 && !only.Contains(part.Id)) continue;
			var obj = new StringBuilder();
			var renderItems = new List<Render.Item>();
			obj.AppendLine("# MeshForge: " + part.Id);
			int vBase = 1;
			int partTris = 0;
			lua.AppendLine("\t" + part.Id + " = {");
			foreach (var spec in part.Meshes)
			{
				var raw = Mesher.Build(spec.Shape, spec.Voxel);
				var mesh = Simplify.Run(raw, spec.Budget);
				Mesher.Finish(mesh, spec.Shape, true);
				V3 center = (mesh.Lo + mesh.Hi) * 0.5, size = mesh.Hi - mesh.Lo;
				WriteObject(obj, spec.Name, mesh, center, ref vBase);
				WriteObject(all, spec.Name, mesh, center, ref allBase);
				int tris = mesh.T.Count / 3;
				var groups = spec.Groups.Count > 0 ? spec.Groups : new List<string> { null };
				partTris += tris * groups.Count;
				if (part.ArmMirror)
				{
					// the mirror image for a left arm (the assembler mirrors its position)
					var flipped = new MeshData();
					foreach (var v in mesh.V) flipped.V.Add(new V3(-v.X, v.Y, v.Z));
					foreach (var n in mesh.N) flipped.N.Add(new V3(-n.X, n.Y, n.Z));
					for (int t = 0; t < mesh.T.Count; t += 3) { flipped.T.Add(mesh.T[t]); flipped.T.Add(mesh.T[t + 2]); flipped.T.Add(mesh.T[t + 1]); }
					V3 fc = new V3(-center.X, center.Y, center.Z);
					WriteObject(obj, spec.Name + "_L", flipped, fc, ref vBase);
					WriteObject(all, spec.Name + "_L", flipped, fc, ref allBase);
				}
				string look = string.Format("Size = Vector3.new({0}, {1}, {2}), Color = Color3.fromRGB({3}, {4}, {5}), Material = Enum.Material.{6}{7}",
					F(size.X), F(size.Y), F(size.Z), spec.Color[0], spec.Color[1], spec.Color[2], spec.Material,
					spec.Transparency > 0 ? ", Transparency = " + F(spec.Transparency) : "");
				foreach (var g in groups)
				{
					V3 pos = center;
					if (g != null && !spec.Local) pos = center - part.GroupPivots[g];
					lua.AppendLine(string.Format("\t\t{{ Mesh = \"{0}\", Pos = Vector3.new({1}, {2}, {3}), {4}{5} }},",
						spec.Name, F(pos.X), F(pos.Y), F(pos.Z), look, g != null ? ", Group = \"" + g + "\"" : ""));
					// the preview: everything in the part frame
					MeshData placed = mesh;
					if (g != null && spec.Local)
					{
						V3 rr = part.GroupRots[g];
						placed = Place(mesh, Rot.Deg(rr.X, rr.Y, rr.Z), part.GroupPivots[g]);
					}
					renderItems.Add(new Render.Item { Mesh = placed, Color = spec.Color, Material = spec.Material });
				}
				Console.WriteLine(string.Format("{0,-36} {1,6} tris (from {2,6}) x{3}  size {4} x {5} x {6}", spec.Name, tris, raw.T.Count / 3, groups.Count, F(size.X), F(size.Y), F(size.Z)));
			}
			lua.AppendLine("\t},");
			totalTris += partTris;
			Console.WriteLine(string.Format("== {0}: {1} triangles on the body", part.Id, partTris));
			File.WriteAllText(Path.Combine(outDir, part.Id + ".obj"), obj.ToString());
			foreach (var it in renderItems)
			{
				it.Mesh.Lo = new V3(1e9, 1e9, 1e9); it.Mesh.Hi = new V3(-1e9, -1e9, -1e9);
				foreach (var v in it.Mesh.V)
				{
					it.Mesh.Lo = new V3(Math.Min(it.Mesh.Lo.X, v.X), Math.Min(it.Mesh.Lo.Y, v.Y), Math.Min(it.Mesh.Lo.Z, v.Z));
					it.Mesh.Hi = new V3(Math.Max(it.Mesh.Hi.X, v.X), Math.Max(it.Mesh.Hi.Y, v.Y), Math.Max(it.Mesh.Hi.Z, v.Z));
				}
			}
			Render.Sheet(Path.Combine(outDir, part.Id + ".png"), renderItems);
		}
		lua.AppendLine("}");
		File.WriteAllText(Path.Combine(outDir, "PartMeshes.luau"), lua.ToString());
		if (only.Count == 0) File.WriteAllText(Path.Combine(outDir, "AllParts.obj"), all.ToString());
		Console.WriteLine("total " + totalTris + " triangles");
		return 0;
	}
}
